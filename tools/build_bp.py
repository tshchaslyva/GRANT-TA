# ---------------------------------------------------------------- авто-висота рядків для довгих текстів (об'єднані клітинки не авто-підганяються)
import math
def merged_width(ws, coord):
    for rng in ws.merged_cells.ranges:
        if coord in rng:
            return sum((ws.column_dimensions[get_column_letter(c)].width or 8.43) for c in range(rng.min_col, rng.max_col + 1)), rng.min_row, rng.max_row
    cell = ws[coord]
    return (ws.column_dimensions[cell.column_letter].width or 8.43), cell.row, cell.row
def fit_rows(ws, coords, pt_per_line=14.4, chars_per_width=1.05, min_height=None):
    for coord in coords:
        v = ws[coord].value
        if not isinstance(v, str) or not v.strip():
            continue
        width, r1, r2 = merged_width(ws, coord)
        cpl = max(20, int(width * chars_per_width))
        lines = sum(max(1, math.ceil(len(part) / cpl)) for part in v.split("\n"))
        need = lines * pt_per_line + 6
        rows = list(range(r1, r2 + 1))
        current = sum((ws.row_dimensions[r].height or 15) for r in rows)
        if need > current:
            per = need / len(rows)
            for r in rows:
                ws.row_dimensions[r].height = per
